"""Frequency traces, delta F and drift fits on synthetic data."""

import numpy as np
import pytest
from scipy.signal import lfilter

from gridtools.calibrate.frequency import (
    count_crossings,
    delta_f_stats,
    fit_drift_variogram,
    resample_track,
    running_quantile,
    semivariogram,
)
from gridtools.io import Track
from gridtools.sim.eod import DriftParams, baseline_frequency


def test_resample_track_takes_bin_medians_and_leaves_gaps_nan() -> None:
    track = Track(
        1, np.array([0.1, 0.4, 0.6, 2.5]), np.array([700.0, 702.0, 760.0, 701.0])
    )
    times, freqs = resample_track(track, 0.0, 3.0, 1.0)
    np.testing.assert_allclose(times, [0.5, 1.5, 2.5])
    assert freqs[0] == pytest.approx(702.0)  # median of 700, 702, 760
    assert np.isnan(freqs[1])
    assert freqs[2] == pytest.approx(701.0)


def test_running_low_quantile_ignores_upward_spikes() -> None:
    values = np.full(200, 700.0)
    values[::10] += 30.0  # chirp-like spikes
    values[50:53] = np.nan
    baseline = running_quantile(values, 21, 0.2)
    np.testing.assert_allclose(baseline[20:-20], 700.0)


def test_count_crossings_uses_hysteresis() -> None:
    d = np.array([5, 0.5, -0.5, 0.4, -3, -2, 0.0, 2, np.nan, 3, -4])
    assert count_crossings(d, 1.0) == 3
    assert count_crossings(d, 0.0) == 5


def test_delta_f_stats_fractions_and_rate() -> None:
    d = np.concatenate([np.full(1800, 4.0), np.full(1800, -30.0)])
    stats = delta_f_stats(d, 1.0)
    assert stats.duration_h == pytest.approx(1.0)
    assert stats.fraction_below[5.0] == pytest.approx(0.5)
    assert stats.fraction_below[50.0] == pytest.approx(1.0)
    assert stats.n_crossings == 1
    assert stats.crossings_per_h == pytest.approx(1.0)


def test_semivariogram_of_white_noise_is_its_variance() -> None:
    rng = np.random.default_rng(0)
    x = rng.normal(0.0, 2.0, 100_000)
    gamma, counts = semivariogram(x, [1, 10, 100])
    np.testing.assert_allclose(gamma, 4.0, rtol=0.03)
    assert counts.tolist() == [99_999, 99_990, 99_900]


def test_trimmed_semivariogram_ignores_rare_jumps() -> None:
    rng = np.random.default_rng(1)
    x = rng.normal(0.0, 1.0, 50_000)
    jumpy = x.copy()
    jumpy[::1000] += 50.0
    plain, _ = semivariogram(jumpy, [5])
    trimmed, _ = semivariogram(jumpy, [5], trim=0.01)
    assert plain[0] > 3.0
    # 1% trimming of Gaussian increments biases the estimate by -7.5%.
    assert trimmed[0] == pytest.approx(0.925, rel=0.05)


def test_drift_fit_recovers_simulator_drift() -> None:
    """Drift generated by gridtools.sim.eod is recovered from its variogram."""
    rng = np.random.default_rng(2)
    params = DriftParams(sd_hz=1.2, timescale_s=20.0, control_rate_hz=1.0)
    gammas = []
    lags = np.unique(np.geomspace(1, 600, 30).round().astype(int))
    for _ in range(8):
        f = baseline_frequency(rng, 20_000, 1.0, 800.0, params)
        gammas.append(semivariogram(f, lags)[0])
    fit = fit_drift_variogram(lags, np.mean(gammas, axis=0))
    assert fit.sd == pytest.approx(1.2, rel=0.15)
    assert fit.timescale_s == pytest.approx(20.0, rel=0.15)
    assert fit.kernel == "gaussian"


def test_exponential_kernel_recovers_ornstein_uhlenbeck() -> None:
    rng = np.random.default_rng(3)
    tau, sd = 15.0, 0.8
    a = np.exp(-1.0 / tau)
    noise = rng.normal(0.0, sd * np.sqrt(1 - a * a), 400_000)
    x = lfilter([1.0], [1.0, -a], noise)
    lags = np.unique(np.geomspace(1, 300, 25).round().astype(int))
    gamma, _ = semivariogram(x, lags)
    fit = fit_drift_variogram(lags, gamma, "exponential")
    assert fit.sd == pytest.approx(sd, rel=0.1)
    assert fit.timescale_s == pytest.approx(tau, rel=0.15)
    gaussian = fit_drift_variogram(lags, gamma, "gaussian")
    assert fit.rms_log_residual < gaussian.rms_log_residual
